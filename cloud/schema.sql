-- ADR-001 store for one profile (the database_name in wrangler.toml). The PC is the only writer
-- of copy_rows and sync_meta; the hosted page only INSERTs into inbox.
-- Apply: npx wrangler d1 execute <database_name> --remote --file cloud/schema.sql

-- Read copy pushed by the sync runner. The runner hashes each row and
-- upserts only changed ones, so `hash` is what it compares against.
-- id is "<kind>:<key>", e.g. "app:42", "posting:<url sha1>", "meta:states".
CREATE TABLE IF NOT EXISTS copy_rows (
  id         TEXT PRIMARY KEY,
  kind       TEXT NOT NULL,
  hash       TEXT NOT NULL,
  json       TEXT NOT NULL CHECK (json_valid(json)),
  updated_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS copy_rows_kind ON copy_rows (kind);

-- Actions appended by the page. D1 serializes writes per database, so seq
-- (AUTOINCREMENT, never reused) is commit order and the runner's cursor
-- "seq > ?" cannot skip a row. uuid is generated by the page and is the
-- replay key in data/inbox-log.jsonl.
CREATE TABLE IF NOT EXISTS inbox (
  seq          INTEGER PRIMARY KEY AUTOINCREMENT,
  uuid         TEXT NOT NULL UNIQUE,
  type         TEXT NOT NULL,
  payload      TEXT NOT NULL CHECK (json_valid(payload)),
  -- What the user saw: {"from": "Evaluated"} for a move, old values for a
  -- settings change, a text hash for a CV edit, NULL for commuting additions.
  precondition TEXT CHECK (precondition IS NULL OR json_valid(precondition)),
  -- Access-verified email, set by the Pages Function from the JWT, never
  -- taken from the request body.
  sender       TEXT NOT NULL,
  created_at   TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  -- Job states are included now because widening a CHECK in SQLite means
  -- rebuilding the table.
  status       TEXT NOT NULL DEFAULT 'pending'
               CHECK (status IN ('pending', 'applied', 'rejected', 'queued', 'running', 'done', 'failed')),
  result       TEXT CHECK (result IS NULL OR json_valid(result)),
  resolved_at  TEXT
);
CREATE INDEX IF NOT EXISTS inbox_status_seq ON inbox (status, seq);

-- Small key/value state: last_push_at, last_pull_at, applied_cursor,
-- copy_version. The page reads last_push_at for "PC last synced".
CREATE TABLE IF NOT EXISTS sync_meta (
  key        TEXT PRIMARY KEY,
  value      TEXT NOT NULL,
  updated_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);
